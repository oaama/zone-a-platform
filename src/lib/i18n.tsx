type Dict = (typeof dict)["ar"];

// Course categories are stored in Arabic in the DB; map them for EN mode.
export const CAT_EN: Record<string, string> = {
  "برمجة": "Programming",
  "تصميم": "Graphics",
  "جرافيكس": "Graphics",
  "لغات": "Languages",
};

export function catName(cat: string, lang: Lang): string {
  return lang === "ar" ? cat : CAT_EN[cat] ?? cat;
}

const LangContext = createContext<{ lang: Lang; t: Dict; toggle: () => void }>({
  lang: "ar",
  t: dict.ar,
  toggle: () => {},
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() =>
    typeof window !== "undefined" && localStorage.getItem("za-lang") === "en" ? "en" : "ar"
  );
  useEffect(() => {
    const saved = (typeof window !== "undefined" && localStorage.getItem("za-lang")) as Lang | null;
    if (saved === "en" || saved === "ar") setLang(saved);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    localStorage.setItem("za-lang", lang);
  }, [lang]);
  const toggle = () => setLang((l) => (l === "ar" ? "en" : "ar"));
  return (
    <LangContext.Provider value={{ lang, t: dict[lang], toggle }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  return useContext(LangContext);
}
